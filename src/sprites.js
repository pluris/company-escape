function bake(rows){
 let w=0;for(const r of rows)w=Math.max(w,r.length);
 const h=rows.length,c=document.createElement("canvas");
 c.width=w;c.height=h;const g=c.getContext("2d");
 for(let y=0;y<h;y++){const r=rows[y];
  for(let x=0;r&&x<r.length;x++){const ch=r[x];if(ch==="."||ch===" ")continue;
   g.fillStyle=PAL[ch]||"#ff00ff";g.fillRect(x,y,1,1);}}
 return c;
}
function whited(img){
 const c=document.createElement("canvas");c.width=img.width;c.height=img.height;
 const g=c.getContext("2d");g.drawImage(img,0,0);
 g.globalCompositeOperation="source-in";g.fillStyle="#ffffff";g.fillRect(0,0,c.width,c.height);
 return c;
}
function shiftStr(r,n){
 if(!n)return r;
 if(n>0)return r.slice(0,Math.max(0,r.length-n))+new Array(Math.min(n,r.length)+1).join(".");
 const m=-n;return new Array(m+1).join(".")+r.slice(m);
}
function walkFrames(baseRows,legRows){
 // two extra frames: legs alternate left/right
 const mk=function(n){
  return bake(baseRows.map(function(r,i){
   return i>=baseRows.length-legRows?shiftStr(r,n):r;
  }));
 };
 return [mk(1),mk(-1)];
}

